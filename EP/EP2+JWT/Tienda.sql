-- Dos roles de aplicacion, nunca confiar en el rol enviado por el cliente al registrarse.
CREATE TABLE roles (
 id_rol TINYINT UNSIGNED PRIMARY KEY,
 nombre VARCHAR(30) NOT NULL UNIQUE
) ENGINE=InnoDB;
INSERT INTO roles VALUES (1,'cliente'),(2,'administrador');

CREATE TABLE usuarios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(60) NOT NULL UNIQUE,
 email VARCHAR(254) NOT NULL UNIQUE,
 rut VARCHAR(12) NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 id_rol TINYINT UNSIGNED NOT NULL DEFAULT 1,
 id_comuna INT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_usuarios_rol FOREIGN KEY (id_rol) REFERENCES roles(id_rol),
 CONSTRAINT fk_usuarios_comuna FOREIGN KEY (id_comuna) REFERENCES comunas(id_co)
) ENGINE=InnoDB;

-- Modelo comercial de referencia: vincularlo a los requerimientos funcionales de EP1.
CREATE TABLE categorias (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL UNIQUE,
 descripcion VARCHAR(500) NULL,
 activa BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;
CREATE TABLE productos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 id_categoria BIGINT UNSIGNED NOT NULL,
 nombre VARCHAR(150) NOT NULL,
 descripcion TEXT NULL,
 precio DECIMAL(12,2) NOT NULL,
 stock INT UNSIGNED NOT NULL DEFAULT 0,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_productos_precio CHECK (precio >= 0),
 CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES categorias(id)
) ENGINE=InnoDB;
CREATE TABLE pedidos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 id_usuario BIGINT UNSIGNED NOT NULL,
 estado ENUM('pendiente','confirmado','cancelado','entregado') NOT NULL DEFAULT 'pendiente',
 total DECIMAL(12,2) NOT NULL DEFAULT 0,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_pedidos_total CHECK (total >= 0),
 CONSTRAINT fk_pedidos_usuario FOREIGN KEY (id_usuario) REFERENCES usuarios(id)
) ENGINE=InnoDB;
CREATE TABLE pedido_detalles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 id_pedido BIGINT UNSIGNED NOT NULL,
 id_producto BIGINT UNSIGNED NOT NULL,
 cantidad INT UNSIGNED NOT NULL,
 precio_unitario DECIMAL(12,2) NOT NULL,
 CONSTRAINT ck_detalles_cantidad CHECK (cantidad > 0),
 CONSTRAINT ck_detalles_precio CHECK (precio_unitario >= 0),
 CONSTRAINT fk_detalles_pedido FOREIGN KEY (id_pedido) REFERENCES pedidos(id),
 CONSTRAINT fk_detalles_producto FOREIGN KEY (id_producto) REFERENCES productos(id),
 UNIQUE KEY uq_pedido_producto (id_pedido,id_producto)
) ENGINE=InnoDB;

